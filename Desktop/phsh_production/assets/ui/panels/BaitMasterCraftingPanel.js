        grid.innerHTML = '';
        console.log('[BaitMaster] Grid cleared, recipes count:', this.recipes.length);
        
        // Debug: Check if wrapped bait recipe is in the recipes
        const wrappedBaitRecipe = this.recipes.find(r => r.id === 'fish_bait_to_wrapped_bait');
