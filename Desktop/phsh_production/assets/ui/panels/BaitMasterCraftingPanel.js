    setupEventListeners() {
        // Close button (matching ToolmasterCraftingPanel pattern)
        document.getElementById('baitmaster-close').addEventListener('click', () => {
            this.close();
        });

        // ESC key to close
        document.addEventListener('keydown', (e) => {
            if (e.key === 'Escape' && this.isOpen()) {
                this.close();
            }
        });
    }

    open() {
        console.log('[BaitMaster] Opening bait master crafting panel');
        const overlay = document.getElementById('baitmaster-overlay');
        overlay.style.display = 'flex';
        
        // Matching exact ToolmasterCraftingPanel behavior
        hytopia.sendData({ type: 'disablePlayerInput' });
        this.addHideChatStyle();
        
        // Hide mobile controls when panel is open
        if (hytopia.isMobile) {
            this.hideMobileControls();
            this.applyMobileStyles();
        }
        
        // Request recipe data from server
        console.log('[BaitMaster] Requesting bait recipes from server');
        hytopia.sendData({ type: 'requestBaitRecipes' });
        
        this.updateDisplay();
        console.log('[BaitMaster] Panel opened, display updated');
    }

    close() {
        const overlay = document.getElementById('baitmaster-overlay');
        overlay.style.display = 'none';
        
        // Matching exact ToolmasterCraftingPanel behavior
        hytopia.sendData({ type: 'enablePlayerInput' });
        this.removeHideChatStyle();
        
        // Show mobile controls when panel is closed
        if (hytopia.isMobile) {
            this.showMobileControls();
        }
        
        // Clear selection
        this.selectedRecipe = null;
        this.selectedQuantity = 1;
        
        // Reset crafting locks when panel closes (matching other panels)
        globalBaitCraftingLock = false;
        this.craftingInProgress = false;
        if (globalBaitCraftingTimeout) {
            clearTimeout(globalBaitCraftingTimeout);
            globalBaitCraftingTimeout = null;
        }
    }

    isOpen() {
        const overlay = document.getElementById('baitmaster-overlay');
        return overlay && overlay.style.display !== 'none';
    }

