    setupArrowNavigation() {
        const scrollContainer = document.getElementById('rod-scroll-container');
        const leftArrow = document.getElementById('rod-arrow-left');
        const rightArrow = document.getElementById('rod-arrow-right');
        
        if (!scrollContainer || !leftArrow || !rightArrow) return;
        
        // Calculate card width and gap
        const getCardWidth = () => {
            if (hytopia.isMobile) {
                return 210; // Mobile card width
            }
            return 280; // Desktop card width
        };
        
        const getGap = () => {
            return 12; // Gap between cards
        };
        
        const getScrollDistance = () => {
            return getCardWidth() + getGap(); // One card width + gap
        };
        
        // Calculate how many cards are visible at once
        const calculateCardsVisible = () => {
            const viewportWidth = scrollContainer.clientWidth;
            const cardWidth = getCardWidth();
            const gap = getGap();
            const cardsVisible = Math.floor(viewportWidth / (cardWidth + gap));
            return Math.max(1, cardsVisible); // At least 1 card visible
        };
        
        // Calculate maximum scroll position based on total rods
        const calculateMaxPosition = () => {
            this.cardsVisible = calculateCardsVisible();
            const totalRods = this.currentRods.length;
            // Maximum position = totalRods - cardsVisible - 1
            // This allows only 1 click right maximum
            this.maxScrollPosition = Math.max(0, totalRods - this.cardsVisible - 1);
            console.log(`[RodShop] Pagination: ${totalRods} rods, ${this.cardsVisible} visible, max position: ${this.maxScrollPosition}`);
        };
        
        // Scroll to a specific position (0-based)
        const scrollToPosition = (position) => {
            const distance = getScrollDistance();
            const targetScroll = position * distance;
            scrollContainer.scrollTo({
                left: targetScroll,
                behavior: 'smooth'
            });
            this.currentScrollPosition = position;
            updateArrowStates();
        };
        
        // Update arrow button states based on current position
        const updateArrowStates = () => {
            leftArrow.disabled = this.currentScrollPosition <= 0;
            rightArrow.disabled = this.currentScrollPosition >= this.maxScrollPosition;
        };
        
        // Initialize pagination
        calculateMaxPosition();
        this.currentScrollPosition = 0; // Start at position 0
        scrollContainer.scrollLeft = 0; // Reset scroll to start
        
        // Left arrow - scroll left by one card
        leftArrow.addEventListener('click', (e) => {
            e.preventDefault();
            e.stopPropagation();
            if (this.currentScrollPosition > 0) {
                scrollToPosition(this.currentScrollPosition - 1);
            }
        });
        
        // Right arrow - scroll right by one card
        rightArrow.addEventListener('click', (e) => {
            e.preventDefault();
            e.stopPropagation();
            if (this.currentScrollPosition < this.maxScrollPosition) {
                scrollToPosition(this.currentScrollPosition + 1);
            }
        });
        
        // Update arrow states on window resize (recalculate if viewport changes)
        let resizeTimeout;
        window.addEventListener('resize', () => {
            clearTimeout(resizeTimeout);
            resizeTimeout = setTimeout(() => {
                calculateMaxPosition();
                // Clamp current position to new max
                if (this.currentScrollPosition > this.maxScrollPosition) {
                    this.currentScrollPosition = this.maxScrollPosition;
                }
                scrollToPosition(this.currentScrollPosition);
            }, 100);
        });
        
        // Initial state update
        updateArrowStates();
    }

