    setupEventListeners() {
        // Close button
        document.getElementById('toolmaster-close').addEventListener('click', () => {
            this.close();
        });

        // ESC key to close
        document.addEventListener('keydown', (e) => {
            if (e.key === 'Escape' && this.isOpen()) {
                this.close();
            }
        });
    }

    setupToolmasterForge(data) {
        // Store item data from server
        this.craftableItems = data.items || [];
        this.playerCoins = data.playerCoins || 0;
        
        // Open the panel
        this.open();
    }

    open() {
        const overlay = document.getElementById('toolmaster-overlay');
        overlay.style.display = 'flex';
        
        hytopia.sendData({ type: 'disablePlayerInput' });
        this.addHideChatStyle();
        
        if (hytopia.isMobile) {
            this.hideMobileControls();
            this.applyMobileStyles();
        }
        
        this.updateDisplay();
    }

    close() {
        const overlay = document.getElementById('toolmaster-overlay');
        overlay.style.display = 'none';
        
        hytopia.sendData({ type: 'enablePlayerInput' });
        this.removeHideChatStyle();
        
        if (hytopia.isMobile) {
            this.showMobileControls();
        }
        
        // Clear selection
        this.selectedItem = null;
        
        // Reset crafting locks when panel closes
        globalToolmasterCraftingLock = false;
        this.craftingInProgress = false;
        if (globalToolmasterCraftingTimeout) {
            clearTimeout(globalToolmasterCraftingTimeout);
            globalToolmasterCraftingTimeout = null;
        }
    }

    isOpen() {
        const overlay = document.getElementById('toolmaster-overlay');
        return overlay && overlay.style.display !== 'none';
    }

    addHideChatStyle() {
        if (!this.styleElement) {
            this.styleElement = document.createElement('style');
            this.styleElement.id = 'toolmaster-crafting-chat-style';
            this.styleElement.textContent = `
                #chat-window {
                    display: none !important;
                }
            `;
            document.head.appendChild(this.styleElement);
        }
    }

    removeHideChatStyle() {
        if (this.styleElement) {
            document.head.removeChild(this.styleElement);
            this.styleElement = null;
        }
    }

