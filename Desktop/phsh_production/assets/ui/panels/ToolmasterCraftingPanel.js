    updateInventory(inventory) {
        this.inventory = inventory;
        if (this.isOpen()) {
            // Only update the details panel to avoid recreating all slots
            this.updateDetailsPanel();
        }
    }

    updateCoins(coins) {
        this.playerCoins = coins;
        if (this.isOpen()) {
            // Only update the details panel to avoid recreating all slots
            this.updateDetailsPanel();
        }
    }

    updateDisplay() {
        this.createItemSlots();
        this.updateDetailsPanel();
    }

    createItemSlots() {
        const grid = document.getElementById('toolmaster-item-grid');
        if (!grid) {
            console.error('[Toolmaster] Item grid element not found!');
            return;
        }
        
        grid.innerHTML = '';

        // Show loading state if no items loaded yet
        if (this.craftableItems.length === 0) {
            const loadingSlot = document.createElement('div');
            loadingSlot.className = 'toolmaster-loading-message';
            loadingSlot.innerHTML = `
                <div style="grid-column: 1 / -1; text-align: center; color: #888; padding: 40px;">
                    Loading forge...
                </div>
            `;
            grid.appendChild(loadingSlot);
            return;
        }
        
        // Create slots for items (up to 15 slots in 3x5 grid)
        const maxSlots = 15;
        for (let i = 0; i < maxSlots; i++) {
            const slot = document.createElement('div');
            slot.className = 'toolmaster-item-slot';
            slot.dataset.slotIndex = i;
            
            const content = document.createElement('div');
            content.className = 'toolmaster-item-slot-content';
            slot.appendChild(content);
            
            // Add item if available
            if (i < this.craftableItems.length) {
                const item = this.craftableItems[i];
                this.populateItemSlot(slot, item, i);
            }
            
            grid.appendChild(slot);
        }
    }

    populateItemSlot(slot, item, index) {
        const content = slot.querySelector('.toolmaster-item-slot-content');
        content.innerHTML = '';
        
        // Create item icon
        const icon = document.createElement('img');
        icon.src = `${this.getAssetBaseUrl()}/ui/icons/${item.sprite}`;
        icon.alt = item.name;
        icon.className = 'toolmaster-item-icon';
        content.appendChild(icon);
        
        // Add quantity indicator if quantity > 1
        if (item.quantity && item.quantity > 1) {
            const quantityBadge = document.createElement('div');
            quantityBadge.style.cssText = 'position: absolute; top: 2px; right: 2px; background: rgba(74, 144, 226, 0.9); color: white; font-size: 10px; font-weight: 600; padding: 2px 4px; border-radius: 3px; line-height: 1;';
            quantityBadge.textContent = `×${item.quantity}`;
            content.style.position = 'relative';
            content.appendChild(quantityBadge);
        }
        
        // Add unified event handler for both mobile and desktop
        const handleSelection = (e) => {
            e.preventDefault();
            e.stopPropagation();
            this.selectItem(item, index);
        };
        
        // Add click handler for desktop
        slot.addEventListener('click', handleSelection);
        
        // Add touch handler for mobile
        if (hytopia.isMobile) {
            slot.addEventListener('touchend', handleSelection);
        }
        
        // Update selection state
        if (this.selectedItem && this.selectedItem.id === item.id) {
            slot.classList.add('selected');
        }
    }

    selectItem(item, index) {
        // Clear previous selection
        document.querySelectorAll('.toolmaster-item-slot.selected').forEach(slot => {
            slot.classList.remove('selected');
        });
        
        // Set new selection
        this.selectedItem = item;
        
        // Highlight selected slot
        const slots = document.querySelectorAll('.toolmaster-item-slot');
        if (slots[index]) {
            slots[index].classList.add('selected');
        }
        
        this.updateDetailsPanel();
    }

