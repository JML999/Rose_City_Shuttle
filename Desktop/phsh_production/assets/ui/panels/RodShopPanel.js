    setupEventListeners() {
        hytopia.onData((data) => {
            if (data.type === 'showRodShop' || data.type === 'updateRodShop') {
                this.setupRodShop(data);
                hytopia.sendData({ type: 'disablePlayerInput' });
            } else if (data.type === 'hideRodStore') {
                const rodShopOverlay = document.getElementById('rod-shop-overlay');
                if (rodShopOverlay) {
                    rodShopOverlay.style.display = 'none';
                }
                
                // Re-enable player input
                hytopia.sendData({ type: 'enablePlayerInput' });
                
                // Restore merchant UI if needed
                this.restoreMerchantUIIfNeeded();
                
                this.isShopOpen = false;
                this.selectedRod = null;
            }
        });

        // Close button
        document.getElementById('rod-shop-close').addEventListener('click', () => {
            this.closeRodShop();
        });

        // Add ESC key handler
        if (!this.escKeyListenerAdded) {
            document.addEventListener('keydown', (event) => {
                if (event.key === 'Escape') {
                    const rodShopOverlay = document.getElementById('rod-shop-overlay');
                    if (rodShopOverlay && rodShopOverlay.style.display !== 'none') {
                        this.closeRodShop();
                    }
                }
            });
            
            this.escKeyListenerAdded = true;
        }
    }

