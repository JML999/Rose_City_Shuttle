    attachShopListeners(rods) {
        const rodShopOverlay = document.getElementById('rod-shop-overlay');
        
        // Rod slot selection listeners
        rodShopOverlay.querySelectorAll('.rod-slot:not(.empty)').forEach(slot => {
            const rodId = slot.getAttribute('data-rod-id');
            const rod = rods.find(r => r.id === rodId);
            
            if (rod) {
                // Simple hover tooltip (desktop only, doesn't interfere with clicks)
                if (!hytopia.isMobile) {
                    slot.addEventListener('mouseenter', () => {
                        this.createRodTooltip(slot, rod);
                    });
                    
                    slot.addEventListener('mouseleave', () => {
                        this.removeRodTooltip(slot);
                    });
                }
                
                // Click handler for selection (original functionality)
                const selectHandler = (e) => {
                    e.preventDefault();
                    
                    // Remove previous selection
                    rodShopOverlay.querySelectorAll('.rod-slot').forEach(s => {
                        s.classList.remove('selected');
                    });
                    
                    // Add selection to clicked slot
                    slot.classList.add('selected');
                    
                    // Update selected rod and show details
                    this.selectedRod = rod;
                    this.showRodDetails(rod);
                    
                    // Tooltip stays visible because cursor is still over the slot
                    // It will only disappear when cursor leaves (mouseleave event)
                };
                
                slot.addEventListener('click', selectHandler);
                slot.addEventListener('touchend', selectHandler);
            }
        });
    }
    
