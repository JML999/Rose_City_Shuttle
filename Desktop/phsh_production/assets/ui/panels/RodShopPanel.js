    positionTooltip(slot, tooltip) {
        // Wait for tooltip to render to get its dimensions
        setTimeout(() => {
            const slotRect = slot.getBoundingClientRect();
            const tooltipRect = tooltip.getBoundingClientRect();
            
            // Position above slot, centered horizontally
            let top = slotRect.top - tooltipRect.height - 8;
            let left = slotRect.left + (slotRect.width / 2) - (tooltipRect.width / 2);
            
            // If tooltip would go above viewport, position below slot instead
            if (top < 10) {
                top = slotRect.bottom + 8;
            }
            
            // Keep tooltip within viewport bounds
            const padding = 10;
            if (left < padding) {
                left = padding;
            } else if (left + tooltipRect.width > window.innerWidth - padding) {
                left = window.innerWidth - tooltipRect.width - padding;
            }
            
            tooltip.style.top = `${top}px`;
            tooltip.style.left = `${left}px`;
        }, 0);
    }
    
    removeRodTooltip(slot) {
        // Tooltip is now in overlay, find it by matching rod ID
        const rodId = slot.getAttribute('data-rod-id');
        const overlay = document.getElementById('rod-shop-overlay');
        if (overlay) {
            const tooltip = overlay.querySelector(`.rod-tooltip[data-rod-id="${rodId}"]`);
            if (tooltip) {
                tooltip.remove();
            }
        }
    }

