    setupEventListeners() {
        // Message handler for showing the shop
        hytopia.onData((data) => {
            console.log('[BoatShopPanel] Received data:', data);
            if (data.type === 'showBoatShop' || data.type === 'updateBoatShop') {
                this.setupBoatShop(data);
                hytopia.sendData({ type: 'disablePlayerInput' });
            } else if (data.type === 'hideBoatStore') {
                console.log('[BoatShopPanel] Hiding boat store');
                this.close();
            }
        });

        // Close button
        document.addEventListener('click', (e) => {
            if (e.target.id === 'boat-shop-close') {
                this.close();
            }
        });

        // ESC key to close
        if (!this.escKeyListenerAdded) {
            document.addEventListener('keydown', (e) => {
                if (e.key === 'Escape' && this.isShopOpen) {
                    this.close();
                }
            });
            this.escKeyListenerAdded = true;
        }

        // Purchase/Spawn button clicks
        const handleButtonPress = (e) => {
            const button = e.target.closest('.boat-card-button');
            if (button && !button.disabled) {
                e.preventDefault();
                e.stopPropagation();
                const boatId = button.getAttribute('data-boat-id');
                if (boatId) {
                    if (button.classList.contains('spawn')) {
                        this.spawnBoat(boatId);
                    } else {
                        this.purchaseBoat(boatId);
                    }
                }
            }
        };
        
        document.addEventListener('click', handleButtonPress);
        document.addEventListener('touchend', handleButtonPress);

        // Handle window resize
        window.addEventListener('resize', () => {
            if (this.isShopOpen) {
                this.resizeAllRenderers();
            }
        });
    }

    resizeAllRenderers() {
        this.boatScenes.forEach((sceneData, boatId) => {
            if (sceneData.container && sceneData.renderer && sceneData.camera) {
                const rect = sceneData.container.getBoundingClientRect();
                if (rect.width > 0 && rect.height > 0) {
                    sceneData.renderer.setSize(rect.width, rect.height);
                    sceneData.camera.aspect = rect.width / rect.height;
                    sceneData.camera.updateProjectionMatrix();
                }
            }
        });
    }

    setupBoatShop(data) {
        const boatShopOverlay = document.getElementById('boat-shop-overlay');
        const boatScrollContainer = document.getElementById('boat-scroll-container');
        
        // Store player data
        this.playerCoins = data.playerCoins || 0;
        this.playerLevel = data.playerLevel || 1;
        this.currentBoats = data.boats || [];
        this.currentPlayerInventory = data.playerInventory || [];
        
        // Reset pagination
        this.currentScrollPosition = 0;
        this.maxScrollPosition = 0;
        this.cardsVisible = 0;
        
        // Show panel
        boatShopOverlay.style.display = 'flex';
        this.isShopOpen = true;

        // Clear existing content
        boatScrollContainer.innerHTML = '';
        this.cleanupAllScenes();

        if (data.boats.length === 0) {
            boatScrollContainer.innerHTML = `
                <div style="width: 100%; text-align: center; color: #888; padding: 40px;">
                    <h3>No Boats Available</h3>
                    <p>Check back later for new boats!</p>
                </div>
            `;
        } else {
            // Create cards for each boat
            data.boats.forEach((boat, index) => {
                this.createBoatCard(boat, index);
            });
            
            // Add three "Coming Soon" placeholder cards
            for (let i = 0; i < 3; i++) {
                this.createComingSoonCard(i);
            }
            
            // Apply mobile styles after cards are created
            if (hytopia.isMobile) {
                setTimeout(() => {
                    this.applyMobileStyles();
                    this.setupArrowNavigation();
                }, 100);
            }
        }
    }

    createBoatCard(boat, index) {
        const boatScrollContainer = document.getElementById('boat-scroll-container');
        
        // Determine card status and styling
        let buttonText = `${boat.value.toLocaleString()} coins`;
        let buttonDisabled = false;
        let buttonClass = 'boat-card-button';
        let statusHtml = '';
        
        if (boat.alreadyOwned) {
            buttonText = 'Spawn Boat';
            buttonClass += ' spawn';
            statusHtml = '<div class="boat-card-status owned">OWNED</div>';
        } else if (!boat.canAfford) {
            buttonDisabled = true;
            statusHtml = '<div class="boat-card-status insufficient-coins">INSUFFICIENT COINS</div>';
        } else if (!boat.levelRequirementMet) {
            buttonDisabled = true;
            statusHtml = `<div class="boat-card-status level-locked">REQUIRES LEVEL ${boat.requiredLevel}</div>`;
        }

        const card = document.createElement('div');
        card.className = 'boat-card';
        card.setAttribute('data-boat-id', boat.id);
        card.innerHTML = `
            <div class="boat-model-container" id="boat-model-${boat.id}">
                <div class="boat-model-loading">Loading model...</div>
                
                <!-- Center overlay: Status, Name, Description -->
                <div class="boat-card-info-overlay">
                    ${statusHtml}
                    <div class="boat-card-name">${boat.name}</div>
                    ${boat.description ? `<div class="boat-card-description">${boat.description}</div>` : ''}
                    ${!boat.alreadyOwned ? `<div class="boat-card-price">${boat.value.toLocaleString()} coins</div>` : ''}
                </div>
            </div>
            
            <!-- Purchase/Spawn button at bottom -->
            <button class="${buttonClass}" data-boat-id="${boat.id}" ${buttonDisabled ? 'disabled' : ''}>
                ${buttonText}
            </button>
        `;
        
        boatScrollContainer.appendChild(card);
        
        // Load 3D model
        this.loadBoatModel(boat);
    }

