    loadBoatModel(boat) {
        if (!this.THREE || !this.GLTFLoader) {
            console.warn('[BoatShopPanel] Three.js not available, skipping 3D model');
            return;
        }

        const container = document.getElementById(`boat-model-${boat.id}`);
        if (!container) return;

        // Clear existing scene
        const existingScene = this.boatScenes.get(boat.id);
        if (existingScene) {
            if (existingScene.animationId) {
                cancelAnimationFrame(existingScene.animationId);
            }
            if (existingScene.renderer) {
                existingScene.renderer.dispose();
            }
            this.boatScenes.delete(boat.id);
        }

        // Initialize Three.js scene for this boat (matching ExperimentalRodShopPanel exactly)
        const scene = new this.THREE.Scene();
        scene.background = null;

        const camera = new this.THREE.PerspectiveCamera(50, 1, 0.1, 1000);
        camera.position.set(0, 0, 4);

        const renderer = new this.THREE.WebGLRenderer({ alpha: true, antialias: true });
        renderer.setPixelRatio(window.devicePixelRatio);
        renderer.shadowMap.enabled = true;
        renderer.shadowMap.type = this.THREE.PCFSoftShadowMap;

        // Lighting (matching ExperimentalRodShopPanel)
        const ambientLight = new this.THREE.AmbientLight(0xffffff, 0.6);
        scene.add(ambientLight);

        const directionalLight = new this.THREE.DirectionalLight(0xffffff, 0.8);
        directionalLight.position.set(5, 5, 5);
        directionalLight.castShadow = true;
        scene.add(directionalLight);

        const fillLight = new this.THREE.DirectionalLight(0x4488ff, 0.3);
        fillLight.position.set(-5, 0, -5);
        scene.add(fillLight);

        // Get model path (matching ExperimentalRodShopPanel pattern)
        const modelPath = 'models/items/boat.gltf';
        const baseUrl = this.getAssetBaseUrl();
        const modelUrl = `${baseUrl}/${modelPath}`;

        const loader = new this.GLTFLoader();
        
        loader.load(
            modelUrl,
            (gltf) => {
                const model = gltf.scene;
                
                // Setup model (center, scale, shadows) - matching ExperimentalRodShopPanel
                const box = new this.THREE.Box3().setFromObject(model);
                const center = box.getCenter(new this.THREE.Vector3());
                const size = box.getSize(new this.THREE.Vector3());
                
                const maxDim = Math.max(size.x, size.y, size.z);
                const scale = 2.5 / maxDim;
                model.scale.setScalar(scale);
                
                const basePosition = {
                    x: -center.x * scale,
                    y: -center.y * scale,
                    z: -center.z * scale
                };
                
                model.position.set(basePosition.x, basePosition.y, basePosition.z);
                
                // Enable shadows
                model.traverse((child) => {
                    if (child.isMesh) {
                        child.castShadow = true;
                        child.receiveShadow = true;
                        if (child.material) {
                            child.material.needsUpdate = true;
                        }
                    }
                });
                
                scene.add(model);
                
                // Resize renderer
                const rect = container.getBoundingClientRect();
                renderer.setSize(rect.width, rect.height);
                camera.aspect = rect.width / rect.height;
                camera.updateProjectionMatrix();
                
                // Append renderer (preserve text overlay) - matching ExperimentalRodShopPanel
                const loadingEl = container.querySelector('.boat-model-loading');
                if (loadingEl) {
                    loadingEl.remove();
                }
                // Insert canvas at the beginning so text overlay stays on top
                container.insertBefore(renderer.domElement, container.firstChild);
                
                // Store scene data
                const sceneData = {
                    scene,
                    camera,
                    renderer,
                    model,
                    animationId: null,
                    container,
                    basePosition
                };
                this.boatScenes.set(boat.id, sceneData);
                
                // Start animation loop (with rotation and floating) - matching ExperimentalRodShopPanel
                const animate = () => {
                    if (model && basePosition) {
                        // Rotation and floating motion (rotation slowed by 50%)
                        model.rotation.y += 0.005;
                        model.position.y = basePosition.y + Math.sin(Date.now() * 0.002) * 0.1;
                        model.position.x = basePosition.x;
                        model.position.z = basePosition.z;
                    }
                    renderer.render(scene, camera);
                    sceneData.animationId = requestAnimationFrame(animate);
                };
                sceneData.animationId = requestAnimationFrame(animate);
            },
            (progress) => {
                // Loading progress (optional)
            },
            (error) => {
                console.error(`[BoatShopPanel] Error loading model for ${boat.id}:`, error);
                container.innerHTML = `
                    <div class="boat-model-loading" style="color: #f44336;">
                        <div style="font-size: 48px; margin-bottom: 8px;">⛵</div>
                        <div>Model unavailable</div>
                    </div>
                `;
            }
        );
    }

    purchaseBoat(boatId) {
        const boat = this.currentBoats?.find(b => b.id === boatId);
        if (!boat || boat.alreadyOwned) return;

        if (!boat.canPurchase) return;

        hytopia.sendData({
            type: 'purchaseBoat',
            boatId: boatId
        });
    }

