    getAssetBaseUrl() {
        if (typeof window.CDN_ASSETS_URL !== 'undefined' && window.CDN_ASSETS_URL) {
            return window.CDN_ASSETS_URL;
        }
        
        const scriptTags = document.getElementsByTagName('script');
        for (let i = 0; i < scriptTags.length; i++) {
            const src = scriptTags[i].src;
            if (src && src.includes('/ui/panels/')) {
                return src.substring(0, src.indexOf('/ui/panels/'));
            }
        }
        
        return window.location.origin;
    }

    show() {
        const overlay = document.getElementById('boat-shop-overlay');
        if (overlay) {
            overlay.style.display = 'flex';
            this.isShopOpen = true;
        }
    }

    close() {
        const overlay = document.getElementById('boat-shop-overlay');
        if (overlay) {
            overlay.style.display = 'none';
            this.isShopOpen = false;
            hytopia.sendData({ type: 'enablePlayerInput' });
        }
        this.cleanupAllScenes();
    }

    cleanupAllScenes() {
        this.boatScenes.forEach((sceneData) => {
            if (sceneData.animationId) {
                cancelAnimationFrame(sceneData.animationId);
            }
            if (sceneData.renderer) {
                sceneData.renderer.dispose();
            }
        });
        this.boatScenes.clear();
    }
